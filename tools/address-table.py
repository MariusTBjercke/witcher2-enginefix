# Writes docs/addresses.md: every fixed game address the DLL uses, per build.
#
# The Steam column comes from the #defines in src/. The GOG column is filled in by hand as the port
# finds each address; this script keeps what is there. Run after adding or moving a define:
#
#     python -I tools/address-table.py           rewrite the file
#     python -I tools/address-table.py --check   exit 1 if it is out of date
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "addresses.md"
SOURCES = ["src/enginefix.c", "src/distance_patch.h", "src/window_patch.h"]
DEFINE = re.compile(r"#define\s+([A-Z][A-Z0-9_]*)\s+0x([0-9A-Fa-f]{8})u?\b(?:\s*//\s*(.*))?")
# Same shape, but values rather than game addresses.
NOT_ADDRESSES = {"IMAGE_BASE", "WF_STYLE_FRAMED"}
RVA_PREFIX = "EF_"          # relative to the image base; the rest are absolute

HEADER = """# Fixed addresses per build

Generated by `tools/address-table.py` from the `#define`s in `src/`; do not edit the Steam column.
The GOG column is kept by the script, so write found addresses there by hand.

Steam addresses are for the unpacked 3.5.0.26 with the image base at `0x00400000`. `EF_` names are
relative to the image base. `IAT_` names are import slots, the rest code or data. An empty GOG cell
means not found yet; see `docs/fixes/gog-build.md`.

| Name | Steam | GOG | Note |
|---|---|---|---|
"""


def gog_column():
    if not DOC.exists():
        return {}
    kept = {}
    for line in DOC.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and cells[0].startswith("`") and cells[2]:
            kept[cells[0].strip("`")] = cells[2]
    return kept


def rows():
    found = {}
    for name in SOURCES:
        text = (ROOT / name).read_text(encoding="utf-8", errors="replace")
        for m in DEFINE.finditer(text):
            key, value, note = m.group(1), m.group(2).upper(), (m.group(3) or "").strip()
            if key in NOT_ADDRESSES:
                continue
            if int(value, 16) < 0x400000 and not key.startswith(RVA_PREFIX):
                continue
            found[key] = (value, note.replace("|", "/"))
    return found


def render():
    gog = gog_column()
    out = [HEADER]
    for key in sorted(rows()):
        value, note = rows()[key]
        out.append(f"| `{key}` | `{value}` | {gog.get(key, '')} | {note} |\n")
    return "".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/addresses.md is out of date; run python -I tools/address-table.py")
            return 1
        print("addresses up to date")
        return 0
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(rows())} addresses")
    return 0


if __name__ == "__main__":
    sys.exit(main())
