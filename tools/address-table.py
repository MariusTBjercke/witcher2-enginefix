# Writes docs/addresses.md: every fixed game address the DLL uses, per build.
#
# The Steam column comes from the #defines in src/. The GOG column comes from the k_gog table in
# src/enginefix.c (0 there = not found on GOG yet), which ga()/ga_rva() read at runtime. Import
# slots are not listed: the DLL finds them by name in the running exe's import directory.
# Run after adding or moving a define or filling in a GOG value:
#
#     python -I tools/address-table.py           rewrite the file
#     python -I tools/address-table.py --check   exit 1 if it is out of date or k_gog lacks a row
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "addresses.md"
SOURCES = ["src/enginefix.c", "src/distance_patch.h", "src/window_patch.h"]
TABLE_SOURCE = "src/enginefix.c"
DEFINE = re.compile(r"#define\s+([A-Z][A-Z0-9_]*)\s+0x([0-9A-Fa-f]{8})u?\b(?:[ \t]*//[ \t]*(.*))?")
PREFIXES = ("VA_", "WF_", "WK_", "EF_", "RVA_")
# Same shape, but values rather than game addresses.
NOT_ADDRESSES = {"WF_STYLE_FRAMED", "WF_STYLE_POPUP"}
RVA_PREFIXES = ("EF_", "RVA_")   # relative to the image base; the rest are absolute
TABLE = re.compile(r"static const ga_row k_gog\[\] = \{(.*?)\n\};", re.S)
ROW = re.compile(r"\{\s*([A-Z][A-Z0-9_]*)\s*,\s*(0x[0-9A-Fa-f]+|0)u?\s*\}")

HEADER = """# Fixed addresses per build

Generated by `tools/address-table.py`; do not edit. The Steam column comes from the `#define`s in
`src/`, the GOG column from the `k_gog` table in `src/enginefix.c`, which the DLL reads at
runtime (`ga()`). To port an address, fill in its `k_gog` value and run the script again.

Steam addresses are for the unpacked 3.5.0.26, GOG addresses for 3.5.0.26g, both at the
preferred image base `0x00400000`; the DLL adds the real load address (the GOG exe has ASLR).
`EF_` and `RVA_` names are relative to the image base, the rest code or data. An empty GOG cell
means not found yet, and the features that need it stay off on GOG; see
`docs/fixes/gog-build.md`. Import slots are not listed: the DLL finds them by name in the
running exe's import directory.

| Name | Steam | GOG | Note |
|---|---|---|---|
"""


def rows():
    found = {}
    for name in SOURCES:
        text = (ROOT / name).read_text(encoding="utf-8", errors="replace")
        for m in DEFINE.finditer(text):
            key, value, note = m.group(1), m.group(2).upper(), (m.group(3) or "").strip()
            if key in NOT_ADDRESSES or not key.startswith(PREFIXES):
                continue
            if int(value, 16) < 0x400000 and not key.startswith(RVA_PREFIXES):
                continue
            found[key] = (value, note.replace("|", "/"))
    return found


def gog_table():
    text = (ROOT / TABLE_SOURCE).read_text(encoding="utf-8", errors="replace")
    m = TABLE.search(text)
    if not m:
        return None
    table = {}
    for key, value in ROW.findall(m.group(1)):
        table[key] = int(value, 16)
    return table


def problems(found, table):
    out = []
    if table is None:
        return [f"no k_gog table in {TABLE_SOURCE}"]
    for key in sorted(set(found) - set(table)):
        out.append(f"{key} has no row in k_gog")
    for key in sorted(set(table) - set(found)):
        out.append(f"k_gog row {key} is not an address #define")
    seen = {}
    for key, (value, _) in found.items():
        if key in table:
            other = seen.setdefault(value, key)
            if other != key:
                out.append(f"{key} and {other} have the same Steam value {value}; ga() looks up by value")
    return out


def render(found, table):
    out = [HEADER]
    for key in sorted(found):
        value, note = found[key]
        gog = table.get(key, 0) if table else 0
        cell = f"`{gog:08X}`" if gog else ""
        out.append(f"| `{key}` | `{value}` | {cell} | {note} |\n")
    return "".join(out)


def main():
    found = rows()
    table = gog_table()
    bad = problems(found, table)
    text = render(found, table)
    if "--check" in sys.argv:
        current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if current.replace("\r\n", "\n") != text:
            bad.append("docs/addresses.md is out of date; run python -I tools/address-table.py")
        for line in bad:
            print(line)
        if bad:
            return 1
        print("addresses up to date")
        return 0
    for line in bad:
        print(line)
    DOC.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(found)} addresses ({sum(1 for v in (table or {}).values() if v)} on GOG)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
